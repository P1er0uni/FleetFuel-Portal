<?php

namespace App\Policies;

use App\Models\User;
use App\Policies\Concerns\DeniesInactiveUsers;

/**
 * Only an administrator manages accounts (Fase 4). Everyone else is refused,
 * whatever the route tries to do.
 */
class UserPolicy
{
    use DeniesInactiveUsers;

    public function viewAny(User $user): bool
    {
        return $user->isAdmin();
    }

    public function view(User $user, User $target): bool
    {
        return $user->isAdmin();
    }

    public function create(User $user): bool
    {
        return $user->isAdmin();
    }

    public function update(User $user, User $target): bool
    {
        return $user->isAdmin();
    }

    public function updateStatus(User $user, User $target): bool
    {
        return $user->isAdmin();
    }

    public function resetPassword(User $user, User $target): bool
    {
        return $user->isAdmin();
    }
}
